#!/usr/bin/env python3
"""Build hskN.js word lists from data/N.json (complete-hsk-vocabulary).

Exact port of HSKCONV.toLine / toText in hanzi-drill.html.
Usage: python3 build.py          # levels 1..7
       python3 build.py 3 5      # only levels 3 and 5
"""
import json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
# JS \s / String.prototype.trim whitespace set (differs from Python's \s)
WS = ' \t\n\v\f\r   -     　﻿'
WS_RE = re.compile('[' + WS + ']+')
MK = {'a': 'āáǎà', 'e': 'ēéěè', 'i': 'īíǐì', 'o': 'ōóǒò', 'u': 'ūúǔù', 'v': 'ǖǘǚǜ'}
JUNK = re.compile(
    r'^(surname |variant of|old variant|also pr|see |abbr\. for|erhua variant|japanese variant)'
    r'|\(archaic\)|archaic variant|unofficial variant|\(onom\.\)|\(dialect\)|abbr\. for|\(Tw\)|Taiwan pr\.',
    re.I | re.A)  # JS /i on ASCII patterns: no non-ASCII case folding
TAIL = re.compile('[;·(' + WS + r']+[^;·]*\Z')


def js_trim(s):
    return re.sub("^[" + WS + "]+|[" + WS + "]+\\Z", "", s)


def mark(s):
    m = re.match(r'([a-z]+?)([1-5])?\Z', s)
    if not m:
        return s
    b, t = m.group(1), int(m.group(2)) if m.group(2) else 5
    if t == 5:
        return b.replace('v', 'ü')
    m2 = re.search('[ae]', b)
    i = m2.start() if m2 else -1
    if i < 0 and 'ou' in b:
        i = b.index('o')
    if i < 0:
        for k in range(len(b) - 1, -1, -1):
            if b[k] in 'iouv':
                i = k
                break
    if i < 0:
        return b
    return (b[:i] + MK[b[i]][t - 1] + b[i + 1:]).replace('v', 'ü')


def mark_py(p):
    return ' '.join(mark(x) for x in p.split(' '))


def norm_py(p):
    return js_trim(WS_RE.sub(' ', re.sub('ü|u:', 'v', str(p))))


def clean(m):
    return js_trim(WS_RE.sub(' ', str(m).replace('|', '/')))


def u16len(s):
    return len(s.encode('utf-16-le', 'surrogatepass')) // 2


def u16slice(s, n):
    return s.encode('utf-16-le', 'surrogatepass')[:2 * n].decode('utf-16-le', 'surrogatepass')


def to_line(e):
    hz = e.get('simplified')
    pos = ''.join(e.get('pos') or [])
    particle = re.search('[yu]', pos) is not None
    forms = []
    for i, f in enumerate(e.get('forms') or []):
        tr = f.get('transcriptions')
        raw = (tr and tr.get('numeric')) or ''
        ms = [x for x in (clean(m) for m in (f.get('meanings') or [])) if x]
        good = [m for m in ms if not JUNK.search(m)]
        cap = re.match('[A-Z]', raw) is not None
        last = norm_py(raw).split(' ')[-1]
        neutral = re.search(r'5\Z|[a-z]\Z', last) is not None
        forms.append(dict(py=norm_py(raw).lower(), ms=good or ms, minor=not good or cap,
                          score=len(good) + (0.5 if particle and neutral else 0), i=i))
    forms = [f for f in forms if f['py']]
    if not forms:
        return None
    major = [f for f in forms if not f['minor']]
    if major:
        forms = major
    forms.sort(key=lambda f: (-f['score'], f['i']))
    seen, use = set(), []
    for f in forms:
        if f['py'] in seen:
            continue
        seen.add(f['py'])
        use.append(f)
    multi = len(use) > 1
    parts = []
    for f in use[:3]:
        t = '; '.join(f['ms'][:2])
        if not t:
            continue
        parts.append('(%s) %s' % (mark_py(f['py']), t) if multi else t)
    mean = ' · '.join(parts)
    if u16len(mean) > 150:
        cut = u16slice(mean, 150)
        mean = TAIL.sub('', cut, count=1) or cut
    return '%s|%s|%s' % (hz, '/'.join(f['py'] for f in use), mean)


def to_text(entries):
    return '\n'.join(l for l in map(to_line, entries) if l)


def build(n):
    with open(os.path.join(HERE, 'data', '%d.json' % n), encoding='utf-8') as fh:
        entries = json.load(fh)
    text = to_text(entries)
    out = ('/* HSK %d word list, generated by build.py from data/%d.json (complete-hsk-vocabulary, MIT; see LICENSE). Do not edit by hand. */\n'
           'window.HSK_WORDS=window.HSK_WORDS||{};\n'
           'window.HSK_WORDS[%d]=%s;\n') % (n, n, n, json.dumps(text, ensure_ascii=False))
    path = os.path.join(HERE, 'hsk%d.js' % n)
    with open(path, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write(out)
    print('level %d: %d words (of %d entries), %d bytes' % (
        n, text.count('\n') + 1 if text else 0, len(entries), os.path.getsize(path)))
    return text


if __name__ == '__main__':
    for n in ([int(a) for a in sys.argv[1:]] or range(1, 8)):
        build(n)
