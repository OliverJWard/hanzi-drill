#!/usr/bin/env python3
"""Build stroke data and the Hanzi Writer vendor files.

`python3 build_strokes.py` regenerates strokes1.js..strokes7.js and
vendor/{hanzi-writer.min.js,hanzi-writer.LICENSE.txt,ARPHICPL.TXT}.
Rerun it after changing the word lists (hskN.js).

Tarballs are downloaded to a cache, verified against their npm sha512
integrity, and read in memory with tarfile (never extracted or executed).
"""
import base64, hashlib, io, json, os, sys, tarfile, tempfile, urllib.request

ROOT = os.path.dirname(os.path.abspath(__file__))
CACHE = os.path.join(tempfile.gettempdir(), "hanzi-drill-npm-cache")  # downloads only, outside the repo
REG = "https://registry.npmjs.org/"
PKGS = {
    "writer": ("hanzi-writer/-/hanzi-writer-3.7.3.tgz",
               "sha512-fdOFrb1cXWL/pV/oplJkcdziCvjJzhhf+qoIBm5IpVGxPBZEu4eLB6ZG5RJDbKXyNbNlyx8oIpa3XrcUBcSXpg=="),
    "data": ("hanzi-writer-data/-/hanzi-writer-data-2.0.1.tgz",
             "sha512-nbQwM+MaryGoq7pBMIZLCd3lFq03nXuJuwku1+6UbjL58uU+9OULVcMkoNvNuJSoIV7f1bbPRfD4D/LQa5S7qg=="),
}
MIN_JS = "package/dist/hanzi-writer.min.js"
HEADER = ("/* Stroke data for HSK %d characters, generated by build_strokes.py from "
          "hanzi-writer-data 2.0.1 (Arphic Public License; see LICENSE). Do not edit by hand. */\n")


def ok(blob, integrity):
    return "sha512-" + base64.b64encode(hashlib.sha512(blob).digest()).decode() == integrity


def fetch(path, integrity):
    os.makedirs(CACHE, exist_ok=True)
    f = os.path.join(CACHE, os.path.basename(path))
    if os.path.exists(f) and ok(open(f, "rb").read(), integrity):
        return open(f, "rb").read()
    with urllib.request.urlopen(REG + path, timeout=120) as r:
        blob = r.read()
    if not ok(blob, integrity):
        sys.exit("ERROR: integrity mismatch for " + path)
    open(f, "wb").write(blob)
    return blob


def read_all(tar):
    """One sequential pass (random access in a .tgz is very slow): {name: bytes}."""
    return {m.name: tar.extractfile(m).read() for m in tar if m.isfile()}


def levels():
    """Return {char: level}, in level-file order (lowest level wins)."""
    chars = {}
    for n in range(1, 8):
        line3 = open(os.path.join(ROOT, "hsk%d.js" % n), encoding="utf-8").read().split("\n")[2]
        words = json.loads(line3[line3.index("=") + 1:].rstrip().rstrip(";"))
        for row in words.split("\n"):
            for c in row.split("|")[0]:
                if "㐀" <= c <= "鿿":
                    chars.setdefault(c, n)
    return chars


def main():
    wtar, dtar = (read_all(tarfile.open(fileobj=io.BytesIO(fetch(*PKGS[k])), mode="r:gz"))
                  for k in ("writer", "data"))
    chars = levels()
    missing, counts, sizes = [], {}, {}
    for n in range(1, 8):
        out = {}
        for c, lv in chars.items():
            if lv != n:
                continue
            name = "package/%s.json" % c
            if name not in dtar:
                missing.append(c)
                print("missing:", c)
                continue
            out[c] = json.loads(dtar[name].decode("utf-8"))
        body = json.dumps(out, ensure_ascii=False, separators=(",", ":"))
        path = os.path.join(ROOT, "strokes%d.js" % n)
        with open(path, "w", encoding="utf-8") as f:
            f.write(HEADER % n + "window.HSK_STROKES=window.HSK_STROKES||{};\n"
                    "Object.assign(window.HSK_STROKES," + body + ");\n")
        counts[n], sizes[path] = len(out), os.path.getsize(path)
    os.makedirs(os.path.join(ROOT, "vendor"), exist_ok=True)
    vend = {"hanzi-writer.min.js": wtar[MIN_JS],
            "hanzi-writer.LICENSE.txt": wtar["package/LICENSE"],
            "ARPHICPL.TXT": dtar["package/ARPHICPL.TXT"]}
    for k, v in vend.items():
        p = os.path.join(ROOT, "vendor", k)
        open(p, "wb").write(v)
        sizes[p] = len(v)
    print("total characters:", len(chars))
    print("per level:", counts)
    print("missing:", missing or "none")
    print("min.js source:", MIN_JS)
    for p, s in sizes.items():
        print("%10d  %s" % (s, p))


if __name__ == "__main__":
    main()
